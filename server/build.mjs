// Bundles the SAME game code the browser runs into one ES module for the Worker.
// Run: node build.mjs   (re-run whenever arcade/sims.js or an engine.js changes)
import { readFileSync, writeFileSync } from 'node:fs';
const r = p => readFileSync(new URL('../' + p, import.meta.url), 'utf8').replace(/\}\)\(this\);\s*$/, '})(globalThis);');
const out = '// AUTO-GENERATED by build.mjs. Do not edit.\n' + ['dip-dash/engine.js', 'portfolio-league/engine.js', 'arcade/sims.js'].map(r).join('\n') +
  '\nexport default globalThis.NNS;\n';
writeFileSync(new URL('./src/sims.bundle.js', import.meta.url), out);
console.log('wrote src/sims.bundle.js', out.length, 'bytes');
